"""Lee un diff y conserva las lineas anadidas en codigo Python de produccion."""
from __future__ import annotations

import re
from pathlib import Path

from unidiff import PatchSet

from debtguard.models import ChangeSet

_EXCLUIR = re.compile(
    r"(^|/)(tests?|testing|migrations)/"
    r"|(^|/)test_[^/]*\.py$|_test\.py$|(^|/)conftest\.py$"
    r"|_pb2(_grpc)?\.py$|(^|/)(generated|autogenerated)/"
)


def es_excluido(ruta: str) -> bool:
    return bool(_EXCLUIR.search(ruta.replace("\\", "/")))


def read_diff(diff_text: str, caso_id: str, origen: str, modelo: str | None,
              ruta_repo: str, base_rev: str = "HEAD") -> ChangeSet:
    cs = ChangeSet(caso_id, origen, modelo, ruta_repo, base_rev)
    for pf in PatchSet(diff_text):
        ruta = pf.path
        if pf.is_removed_file or pf.is_binary_file or not ruta.endswith(".py"):
            continue
        if es_excluido(ruta):
            cs.excluidos.append(ruta)
            continue
        anadidas: list[int] = []
        for hunk in pf:
            for ln in hunk:
                if ln.is_added:
                    anadidas.append(ln.target_line_no)
                    if ln.value.strip():
                        cs.lineas_anadidas += 1
                elif ln.is_removed and ln.value.strip():
                    cs.lineas_eliminadas += 1
        if anadidas:
            cs.archivos[ruta] = anadidas
    return cs


def read_diff_file(path: str | Path, **kw) -> ChangeSet:
    return read_diff(Path(path).read_text(encoding="utf-8", errors="replace"), **kw)
